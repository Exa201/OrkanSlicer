/** End-to-end test for the pure G-code preparation stage used before printer upload. */
public final class AnycubicGCodeProcessorTest {
    public static void main(String[] args) throws Exception {
        testFullAnycubicRewrite();
        testWeightedMassAndDesktopPaletteFormat();
        testIncompletePerFilamentMassesAreFilled();
        testZeroDensityGetsAUsableFallback();
        testReportedDesktopMassAndTemperaturesArePreserved();
        testDefaultToolInsertion();
        testMissingLivePreviewDoesNotAddBrandedPlaceholder();
        testMissingHeaderIsRejected();
        testInvalidToolDoesNotLeavePartialUpload();
        testLargeFilePasses();
        testThumbnailRowsAreWrappedWithoutLosingData();
        if (args.length > 0) {
            for (String path : args) testActivePrinterFile(path);
        }
        System.out.println("AnycubicGCodeProcessorTest passed: metadata, slots, thumbnails and large files.");
    }

    private static void testFullAnycubicRewrite() throws Exception {
        File source = tempFile("anycubic-source", ".gcode");
        File target = tempFile("anycubic-result", ".gcode");
        write(source,
                "; generated by Slice Beam 1.0\n" +
                "; filament_density = 1.24\n" +
                "; filament used [cm3] = 10,20\n" +
                "; filament_type = PLA,PETG\n" +
                "; filament_colour = #111111,#222222\n" +
                "; object_label = Türgriff\n" +
                "; filament_colour_type = legacy\n" +
                "; HEADER_BLOCK_END\n" +
                "M106 S0\nT0\nT1 ; switch\n; filament: 1,2\n" +
                "; total filament used [g] = 0\nG1 X10\n");
        AnycubicGCodeProcessor.ScanResult scan = AnycubicGCodeProcessor.scan(source);
        equal(1, scan.maxTool, "max tool");
        equal(30.0, scan.volume, "volume");
        AnycubicGCodeProcessor.Options options = options(new int[]{1, 0}, new int[]{1, 0});
        options.modelInstances = 3;
        options.paintInfo = "[{\"paint_index\":1}]";
        options.colors = "#AA0000;#00AA00";
        options.materials = "PLA;PETG";
        options.smallThumbnail = "; thumbnail begin 230x110 dGVzdA==\n; THUMBNAIL_BLOCK_END\n";
        options.largeThumbnail = "; thumbnail begin 512x512 ZGVtbw== top\n; THUMBNAIL_BLOCK_END\n";
        check(AnycubicGCodeProcessor.rewrite(source, target, scan, options), "header must be rewritten");
        String output = read(target);
        contains(output, "; generated by OrcaSlicer 1.0", "slicer name");
        contains(output, "; model_instances: 3", "model count");
        contains(output, "; source_info:", "source metadata");
        contains(output, "; paint_info = [{\"paint_index\":1}]", "paint metadata");
        contains(output, "; project_info =", "ACE project metadata");
        contains(output, "; filament: 2,1", "filament map");
        contains(output, "; filament used [g] = 12.40,24.80", "per-filament mass metadata");
        contains(output, "; total filament used [g] = 37.20", "total mass metadata");
        contains(output, "; filament_colour = #AA0000;#00AA00", "color palette");
        contains(output, "; filament_type = PLA;PETG", "material palette");
        contains(output, "; object_label = Türgriff", "UTF-8 model labels");
        contains(output, "T1\nT0 ; switch", "tool remapping");
        contains(output, "; thumbnail begin 230x110", "preview thumbnail");
        contains(output, "; thumbnail begin 512x512", "top thumbnail");
        excludes(output, "filament_colour_type", "unsupported legacy option");
        delete(source, target);
    }

    private static void testWeightedMassAndDesktopPaletteFormat() throws Exception {
        File source = tempFile("anycubic-weighted-mass", ".gcode");
        File target = tempFile("anycubic-weighted-mass-result", ".gcode");
        write(source,
                "; filament_density: 1.23,1.05\n" +
                "; filament used [cm3] = 2.00,3.00\n" +
                "; HEADER_BLOCK_END\n" +
                "; filament_density = 1.23,1.05\n" +
                "; filament_colour = #AAAAAA,#BBBBBB\n" +
                "; filament_type = PETG,ABS\n" +
                "; total filament used [g] = 0.00\n");
        AnycubicGCodeProcessor.ScanResult scan = AnycubicGCodeProcessor.scan(source);
        equal(5.61, scan.totalMass, "weighted mass using each filament density");
        equal(1.05, scan.densities[1], "second filament density");

        AnycubicGCodeProcessor.Options options = options(new int[]{0, 1}, new int[]{0, 1});
        options.colors = AnycubicGCodeProcessor.formatMappedPalette(new int[]{0, 1}, Arrays.asList(
                new FilamentSlot(0xFFAA0000, "PETG"), new FilamentSlot(0xFF00AA00, "ABS")), true);
        options.materials = AnycubicGCodeProcessor.formatMappedPalette(new int[]{0, 1}, Arrays.asList(
                new FilamentSlot(0xFFAA0000, "PETG"), new FilamentSlot(0xFF00AA00, "ABS")), false);
        check(AnycubicGCodeProcessor.rewrite(source, target, scan, options), "weighted-mass file must be rewritten");
        String output = read(target);
        contains(output, "; filament_density: 1.23,1.05", "all density values in header");
        contains(output, "; filament_density = 1.23,1.05", "all density values in settings metadata");
        contains(output, "; filament used [g] = 2.46,3.15", "weighted per-filament masses");
        contains(output, "; total filament used [g] = 5.61", "weighted total mass");
        contains(output, "; filament_colour = #AA0000;#00AA00", "desktop-compatible color separators");
        contains(output, "; filament_type = PETG;ABS", "desktop-compatible material separators");
        delete(source, target);
    }

    private static void testReportedDesktopMassAndTemperaturesArePreserved() throws Exception {
        File source = tempFile("anycubic-desktop-reference", ".gcode");
        File target = tempFile("anycubic-desktop-reference-result", ".gcode");
        write(source,
                "; generated by AnycubicSlicerNext 2.0.0.3\n" +
                "; filament_density: 1.23,1.05,1.23\n" +
                "; filament used [cm3] = 2.67,0.00,0.00\n" +
                "; filament used [g] = 3.29,0.00,0.00\n" +
                "; total filament used [g] = 3.29\n" +
                "; HEADER_BLOCK_END\n" +
                "; filament_density = 1.23,1.05,1.23\n" +
                "; filament_type = PETG;ABS;TPU\n" +
                "; filament_colour = #212721;#FF6A14;#75787B\n" +
                "; pressure_advance = 0.05,0.05,0.05\n" +
                "; z_offset = 0\n" +
                "G9111 bedTemp=70 extruderTemp=230\nM900 K0.051\nT0\n");
        AnycubicGCodeProcessor.ScanResult scan = AnycubicGCodeProcessor.scan(source);
        equal(3.29, scan.totalMass, "desktop slicer's precise total mass");
        AnycubicGCodeProcessor.Options options = options(new int[]{1}, new int[]{1});
        options.colors = "#112233;#445566";
        options.materials = "PETG;ABS";
        check(AnycubicGCodeProcessor.rewrite(source, target, scan, options), "desktop reference must be rewritten");
        String output = read(target);
        contains(output, "; filament_density: 1.23,1.05,1.23", "three densities preserved");
        contains(output, "; filament_density = 1.23,1.05,1.23", "three detailed densities preserved");
        contains(output, "; filament used [g] = 3.29,0.00,0.00", "per-filament mass kept from desktop");
        contains(output, "; total filament used [g] = 3.29", "precise desktop total preserved");
        contains(output, "G9111 bedTemp=70 extruderTemp=230", "desktop first-layer temperatures preserved");
        contains(output, "M900 K0.051", "desktop Kobra pressure command preserved");
        contains(output, "; pressure_advance = 0.05,0.05,0.05", "pressure advance remains filament metadata");
        contains(output, "; z_offset = 0", "Z offset remains independent metadata");
        contains(output, "T1", "selected physical tool mapping applied");
        excludes(output, "; filament_colour = #112233,#445566", "comma-delimited Anycubic palette");
        delete(source, target);
    }

    private static void testZeroDensityGetsAUsableFallback() throws Exception {
        File source = tempFile("anycubic-zero-density", ".gcode");
        File target = tempFile("anycubic-zero-density-result", ".gcode");
        write(source,
                "; filament_density: 0\n" +
                "; filament used [cm3] = 4.36\n" +
                "; HEADER_BLOCK_END\n" +
                "; filament_density = 0\n" +
                "; total filament used [g] = 0.00\n");
        AnycubicGCodeProcessor.ScanResult scan = AnycubicGCodeProcessor.scan(source);
        equal(1.24, scan.density, "safe default for an unset material density");
        equal(5.4064, scan.totalMass, "mass derived when source density and mass are missing");
        check(AnycubicGCodeProcessor.rewrite(source, target, scan,
                options(new int[]{0}, new int[]{0})), "zero-density file must be recoverable");
        String output = read(target);
        contains(output, "; filament_density: 1.24", "invalid zero density replaced in header");
        contains(output, "; filament_density = 1.24", "invalid zero density replaced in metadata");
        contains(output, "; filament used [g] = 5.41", "missing mass derived from volume and fallback density");
        contains(output, "; total filament used [g] = 5.41", "missing total mass repaired");
        delete(source, target);
    }

    private static void testIncompletePerFilamentMassesAreFilled() throws Exception {
        File source = tempFile("anycubic-partial-mass", ".gcode");
        File target = tempFile("anycubic-partial-mass-result", ".gcode");
        write(source,
                "; filament_density: 1.23,1.05\n" +
                "; filament used [cm3] = 2.00,3.00\n" +
                "; filament used [g] = 2.46,0.00\n" +
                "; HEADER_BLOCK_END\n" +
                "; total filament used [g] = 0.00\n");
        AnycubicGCodeProcessor.ScanResult scan = AnycubicGCodeProcessor.scan(source);
        equal(5.61, scan.totalMass, "partial mass list merged with the missing filament's volume");
        check(scan.needsMassBreakdownRewrite, "missing used-filament mass should request a metadata repair");
        check(AnycubicGCodeProcessor.rewrite(source, target, scan,
                options(new int[]{0, 1}, new int[]{0, 1})), "partial mass file must be rewritten");
        String output = read(target);
        contains(output, "; filament used [g] = 2.46,3.15", "partial per-filament mass repaired");
        contains(output, "; total filament used [g] = 5.61", "partial total mass repaired");
        delete(source, target);
    }

    private static void testDefaultToolInsertion() throws Exception {
        File source = tempFile("anycubic-default", ".gcode");
        File target = tempFile("anycubic-default-result", ".gcode");
        write(source, "; HEADER_BLOCK_END\nM106 S0\nG1 X5\n");
        AnycubicGCodeProcessor.ScanResult scan = AnycubicGCodeProcessor.scan(source);
        check(AnycubicGCodeProcessor.rewrite(source, target, scan,
                options(new int[]{1}, new int[]{1})), "simple header must be rewritten");
        String output = read(target);
        contains(output, "; filament start gcode\nT1\nM106 S0", "default tool follows the selected physical tool");
        delete(source, target);
    }

    private static void testMissingLivePreviewDoesNotAddBrandedPlaceholder() throws Exception {
        File source = tempFile("anycubic-no-live-preview", ".gcode");
        File target = tempFile("anycubic-no-live-preview-result", ".gcode");
        write(source, "; HEADER_BLOCK_END\nM106 S0\nG1 X15 Y20 E0.5\n");
        AnycubicGCodeProcessor.Options options = options(new int[]{0}, new int[]{0});
        options.smallThumbnail = "";
        options.largeThumbnail = "";
        check(AnycubicGCodeProcessor.rewrite(source, target, AnycubicGCodeProcessor.scan(source), options),
                "G-code must remain uploadable if viewport capture is unavailable");
        String output = read(target);
        contains(output, "G1 X15 Y20 E0.5", "model motion remains in uploaded G-code");
        excludes(output, "thumbnail begin", "an unavailable preview is not replaced with an empty thumbnail");
        delete(source, target);
    }

    private static void testInvalidToolDoesNotLeavePartialUpload() throws Exception {
        File source = tempFile("anycubic-invalid", ".gcode");
        File target = tempFile("anycubic-invalid-result", ".gcode");
        write(source, "; HEADER_BLOCK_END\nT2\n");
        boolean rejected = false;
        try {
            AnycubicGCodeProcessor.rewrite(source, target, AnycubicGCodeProcessor.scan(source),
                    options(new int[]{1, 0}, new int[]{1, 0}));
        } catch (IllegalArgumentException expected) {
            rejected = true;
        }
        check(rejected, "unmapped tool must fail");
        check(!target.exists(), "failed rewrite must remove its partial output");
        delete(source, target);
    }

    private static void testMissingHeaderIsRejected() throws Exception {
        File source = tempFile("anycubic-no-header", ".gcode");
        File target = tempFile("anycubic-no-header-result", ".gcode");
        write(source, "; generated file without a complete metadata header\nT0\nG1 X5\n");
        AnycubicGCodeProcessor.ScanResult scan = AnycubicGCodeProcessor.scan(source);
        check(!AnycubicGCodeProcessor.rewrite(source, target, scan,
                options(new int[]{0}, new int[]{0})), "missing header must be rejected");
        check(!target.exists(), "rejected file must not leave an upload candidate");
        delete(source, target);
    }

    private static void testLargeFilePasses() throws Exception {
        File source = tempFile("anycubic-large", ".gcode");
        File target = tempFile("anycubic-large-result", ".gcode");
        try (BufferedWriter writer = new BufferedWriter(new FileWriter(source))) {
            writer.write("; HEADER_BLOCK_END\n");
            for (int i = 0; i < 120_000; i++) {
                writer.write(i % 2 == 0 ? "T0\n" : "T1 ; change\n");
                writer.write("G1 X123.45 Y67.89 E0.0123\n");
            }
        }
        AnycubicGCodeProcessor.ScanResult scan = AnycubicGCodeProcessor.scan(source);
        equal(1, scan.maxTool, "large-file max tool");
        check(AnycubicGCodeProcessor.rewrite(source, target, scan,
                options(new int[]{1, 0}, new int[]{1, 0})), "large file must be rewritten");
        long toolLines = 0;
        try (BufferedReader reader = new BufferedReader(new FileReader(target))) {
            String line;
            while ((line = reader.readLine()) != null) {
                if (line.equals("T1") || line.equals("T0 ; change")) toolLines++;
            }
        }
        equal(120_000L, toolLines, "large-file remapped command count");
        check(target.length() > source.length(), "large output should include printer metadata and thumbnails");
        delete(source, target);
    }

    private static void testThumbnailRowsAreWrappedWithoutLosingData() {
        String encoded = "ABCDEFGHIJKLMNOPQRSTUVWXYZ".repeat(170);
        String block = AnycubicGCodeProcessor.formatThumbnailBlock(512, 512, encoded, true);
        contains(block, "; thumbnail begin 512x512 " + encoded.length() + " top", "thumbnail header");
        StringBuilder recovered = new StringBuilder();
        for (String line : block.split("\\n")) {
            if (line.startsWith("; ") && !line.startsWith("; THUMBNAIL_")
                    && !line.startsWith("; thumbnail ")) {
                String data = line.substring(2);
                check(data.length() <= 76, "thumbnail rows must not exceed 76 characters");
                recovered.append(data);
            }
        }
        equal(encoded, recovered.toString(), "thumbnail data round trip");
        check(block.endsWith("; thumbnail end\n; THUMBNAIL_BLOCK_END\n"), "thumbnail block end");
    }

    private static void testActivePrinterFile(String path) throws Exception {
        File source = new File(path);
        File target = tempFile("anycubic-live-result", ".gcode");
        AnycubicGCodeProcessor.ScanResult scan = AnycubicGCodeProcessor.scan(source);
        int[] map = new int[Math.max(1, scan.maxTool + 1)];
        for (int i = 0; i < map.length; i++) map[i] = (i + 1) % 2;
        int[] gates = new int[map.length];
        for (int i = 0; i < gates.length; i++) gates[i] = map[i];
        AnycubicGCodeProcessor.Options options = options(map, gates);
        options.smallThumbnail = "; thumbnail begin 230x110 dGVzdA==\n; THUMBNAIL_BLOCK_END\n";
        options.largeThumbnail = "; thumbnail begin 512x512 ZGVtbw== top\n; THUMBNAIL_BLOCK_END\n";
        check(AnycubicGCodeProcessor.rewrite(source, target, scan, options),
                "active printer G-code header must be rewritten");
        AnycubicGCodeProcessor.ScanResult result = AnycubicGCodeProcessor.scan(target);
        check(result.maxTool <= 1, "active file tools should map only to ACE T0/T1");
        check(GCodeIntegrityValidator.validate(target).isValid(),
                "prepared active printer file should retain all print layers");
        String sourceText = read(source);
        String output = read(target);
        contains(output, "; project_info =", "live file ACE metadata");
        contains(output, "; thumbnail begin 512x512", "live file thumbnail");
        if (!scan.hasToolSelection) {
            contains(output, "; filament start gcode\nT1\n", "selected tool inserted when source has no tool command");
        }
        for (String line : sourceText.split("\\n")) {
            String trimmed = line.trim();
            if (trimmed.startsWith("G9111 ") || trimmed.startsWith("M900 ")) {
                contains(output, trimmed, "printer start command preserved: " + trimmed);
            }
        }
        delete(target);
    }

    private static AnycubicGCodeProcessor.Options options(int[] tools, int[] gates) {
        AnycubicGCodeProcessor.Options options = new AnycubicGCodeProcessor.Options();
        options.remappedTools = tools;
        options.gates = gates;
        options.versionName = "test";
        options.smallThumbnail = "; thumbnail begin 230x110 dGVzdA==\n; THUMBNAIL_BLOCK_END\n";
        options.largeThumbnail = "; thumbnail begin 512x512 ZGVtbw== top\n; THUMBNAIL_BLOCK_END\n";
        return options;
    }

    private static File tempFile(String prefix, String suffix) throws IOException {
        File file = Files.createTempFile(prefix, suffix).toFile();
        file.deleteOnExit();
        return file;
    }

    private static void write(File file, String text) throws IOException {
        Files.write(file.toPath(), text.getBytes(java.nio.charset.StandardCharsets.UTF_8));
    }

    private static String read(File file) throws IOException {
        return new String(Files.readAllBytes(file.toPath()), java.nio.charset.StandardCharsets.UTF_8)
                .replace("\r\n", "\n").replace('\r', '\n');
    }

    private static void delete(File... files) {
        for (File file : files) if (file.exists()) file.delete();
    }

    private static void contains(String value, String expected, String label) {
        if (!value.contains(expected)) throw new AssertionError("Missing " + label + ": " + expected);
    }

    private static void excludes(String value, String expected, String label) {
        if (value.contains(expected)) throw new AssertionError("Unexpected " + label + ": " + expected);
    }

    private static void check(boolean value, String label) {
        if (!value) throw new AssertionError("Expected: " + label);
    }

    private static void equal(long expected, long actual, String label) {
        if (expected != actual) throw new AssertionError(label + ": expected " + expected + ", got " + actual);
    }

    private static void equal(int expected, int actual, String label) {
        equal((long) expected, actual, label);
    }

    private static void equal(double expected, double actual, String label) {
        if (Math.abs(expected - actual) > 0.0001)
            throw new AssertionError(label + ": expected " + expected + ", got " + actual);
    }

    private static void equal(String expected, String actual, String label) {
        if (!expected.equals(actual)) throw new AssertionError(label + ": expected data to match");
    }
}
